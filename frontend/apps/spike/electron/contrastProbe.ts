/**
 * Returns renderer JS that measures WCAG contrast between two CSS colors.
 */
export function contrastProbeSource(): string {
  return [
    "function srgbChannel(value) {",
    "  var c = value / 255;",
    "  return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);",
    "}",
    "function parseRgb(color) {",
    "  var canvas = document.createElement('canvas');",
    "  var ctx = canvas.getContext('2d');",
    "  if (!ctx) return null;",
    "  ctx.fillStyle = '#000';",
    "  ctx.fillStyle = color;",
    "  var computed = String(ctx.fillStyle);",
    "  if (computed.charAt(0) === '#' && computed.length === 7) {",
    "    return {",
    "      r: parseInt(computed.slice(1, 3), 16),",
    "      g: parseInt(computed.slice(3, 5), 16),",
    "      b: parseInt(computed.slice(5, 7), 16)",
    "    };",
    "  }",
    "  var start = computed.indexOf('(');",
    "  var end = computed.indexOf(')');",
    "  if (start < 0 || end < 0) return null;",
    "  var parts = computed.slice(start + 1, end).split(',');",
    "  if (parts.length < 3) return null;",
    "  return {",
    "    r: Number(parts[0]),",
    "    g: Number(parts[1]),",
    "    b: Number(parts[2])",
    "  };",
    "}",
    "function luminance(color) {",
    "  var rgb = parseRgb(color);",
    "  if (!rgb) return 0;",
    "  var r = srgbChannel(rgb.r);",
    "  var g = srgbChannel(rgb.g);",
    "  var b = srgbChannel(rgb.b);",
    "  return 0.2126 * r + 0.7152 * g + 0.0722 * b;",
    "}",
    "function contrastRatio(a, b) {",
    "  var l1 = luminance(a);",
    "  var l2 = luminance(b);",
    "  var lighter = Math.max(l1, l2);",
    "  var darker = Math.min(l1, l2);",
    "  return (lighter + 0.05) / (darker + 0.05);",
    "}",
    "function measurePair(name, foreground, background, minimum) {",
    "  var ratio = contrastRatio(foreground, background);",
    "  return {",
    "    name: name,",
    "    ratio: ratio,",
    "    minimum: minimum,",
    "    pass: ratio >= minimum,",
    "    foreground: foreground,",
    "    background: background",
    "  };",
    "}",
  ].join("\n");
}
